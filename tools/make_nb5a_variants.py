"""Generate notebooks/NB5a_variants.ipynb (development variants of the LightGBM bank, D34). Run after NB5a."""
from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
nb = nbf.v4.new_notebook()
md, code = nbf.v4.new_markdown_cell, nbf.v4.new_code_cell

nb.cells = [
    md("# NB5a variants — development variants of the LightGBM bank (validation units only)\n\n"
       "D34. The first NB5a run (bank of guide §5.2, forecasting the index level) barely beat persistence and lost "
       "to CLIPER on the validation units. Four variants of the forecasting interface are compared on the same "
       "units, origins, issue rows, prior and scores, with the setting rule 1 chose for the level bank on "
       "20 Nov 2026 (num_leaves 15, learning rate 0.03, min_data_in_leaf 200), pinned here so this record stays "
       "reproducible:\n"
       "- **level**: forecast k(t + h) (guide §5.2, the first NB5a run);\n"
       "- **change**: forecast k(t + h) − k(t), then add k(t) back (persistence anchor);\n"
       "- **level, pooled**: one model per quantile for all horizons, with h as a feature (guide §5.2 ablation);\n"
       "- **change, pooled**: both.\n\n"
       "Development data only; every variant counts as a LightGBM development round (D34). The baselines come from "
       "NB5a (they do not depend on LightGBM)."),
    code("import os, sys, time, json, hashlib\n"
         "from pathlib import Path\n"
         "import numpy as np, pandas as pd, yaml\n"
         "ROOT = Path.cwd().resolve()\n"
         "ROOT = ROOT.parent if ROOT.name == 'notebooks' else ROOT\n"
         "sys.path.insert(0, str(ROOT / 'src'))\n"
         "os.environ['PYTHONPATH'] = str(ROOT / 'src') + os.pathsep + os.environ.get('PYTHONPATH', '')\n"
         "os.environ.setdefault('LOKY_MAX_CPU_COUNT', str(os.cpu_count()))\n"
         "from joblib import Parallel, delayed\n"
         "from pvcold import config as C, audit as A, fleet as F, forecast as FC\n"
         "pd.set_option('display.width', 200); pd.set_option('display.max_columns', 40)\n"
         "N_JOBS = os.cpu_count(); t0 = time.time()\n"
         "nb5 = json.loads((C.RESULTS / 'nb5a_dev' / 'summary.json').read_text())   # source of the baseline forecasts\n"
         "LGB_PARAMS = {'num_leaves': 15, 'learning_rate': 0.03, 'min_data_in_leaf': 200}   # pinned: rule 1 for the level bank (D34)\n"
         "PRIOR = yaml.safe_load((C.RESULTS / 'nb3_index' / 'frozen_config_part1.yaml').read_text())['prior_variant']\n"
         "ALT = json.loads((C.RESULTS / 'nb1_audit' / 'summary.json').read_text())['campus_altitude_m']\n"
         "p = F.load_panel(); del p['targets15_kW']\n"
         "E = p['events'].set_index('event'); U = p['units']; geo15 = p['geometry15']\n"
         "VAL = E.index[E.set == 'validation'].tolist()\n"
         "idx = {k: pd.read_parquet(C.RESULTS / 'nb3_index' / f'{k}.parquet').set_index('time') for k in ['k_cens', 'sigma', 'c', 'n']}\n"
         "gains3 = pd.read_csv(C.RESULTS / 'nb3_index' / 'gains.csv')\n"
         "base = pd.read_parquet(C.RESULTS / 'nb5a_dev' / 'val_forecasts.parquet').query(\"model != 'LGB'\")   # baselines only\n"
         "print('LightGBM setting (pinned):', LGB_PARAMS, '| baseline rows:', len(base), sorted(base.model.unique()))"),
    code("VARIANTS = [('level', False), ('change', False), ('level', True), ('change', True)]\n"
         "tasks = []\n"
         "for v in VAL:\n"
         "    s = E.loc[v, 'start']; S = FC.event_series(v, idx, geo15)\n"
         "    for d in FC.ORIGIN_DAYS:\n"
         "        o = s + pd.Timedelta(days=d)\n"
         "        for tg, pl in VARIANTS:\n"
         "            tasks.append((v, S, o, min(o + pd.Timedelta(days=30), s + pd.Timedelta(days=90)), tg, pl))\n"
         "t1 = time.time()\n"
         "res = Parallel(n_jobs=N_JOBS)(delayed(FC.variant_task)(v, S, o, e, LGB_PARAMS, tg, pl) for v, S, o, e, tg, pl in tasks)\n"
         "var = pd.concat([r[2] for r in res], ignore_index=True)\n"
         "fc = pd.concat([base, var.astype({c: 'float32' for c in var.columns if c.startswith('q')})], ignore_index=True)\n"
         "MODELS = sorted(fc.model.unique())\n"
         "print('%d tasks in %.0f s; models: %s' % (len(tasks), time.time() - t1, MODELS))"),
    code("QC = [f'q{t:.1f}' for t in FC.TAUS]\n"
         "lv, gl = FC.member_levels()\n"
         "Tcache, srows = {}, []\n"
         "for v in VAL:\n"
         "    assert E.loc[v, 'set'] == 'validation'\n"
         "    a = F.event_arrays(v, p)\n"
         "    g = gains3[gains3.event == v].set_index('donor')['gain'].reindex(a['dn'])\n"
         "    pr, _, _, _ = F.event_priors(a, g, U, ALT, Tcache)\n"
         "    B = np.asarray(pr['B_' + PRIOR]); g_m = FC.gain_members(pr[PRIOR], B / np.median(B), gl)\n"
         "    f = fc[fc.event == v].copy()\n"
         "    f['target'] = f['t'] + pd.to_timedelta(15 * f['h'], unit='min')\n"
         "    f['y'] = p['y15'][E.loc[v, 'units']].reindex(f['target']).to_numpy()\n"
         "    f['gt'] = geo15['Gt'].reindex(f['target']).to_numpy()\n"
         "    good = f[QC].notna().all(axis=1) & np.isfinite(f['y'])\n"
         "    cnt = f[good].groupby(['h', 't'])['model'].nunique()\n"
         "    keep = cnt[cnt == len(MODELS)].index\n"
         "    f = f.set_index(['h', 't']).loc[lambda x: x.index.isin(keep)].reset_index()\n"
         "    for (m, h), x in f.groupby(['model', 'h']):\n"
         "        Y = FC.power_members(x[QC].to_numpy(dtype=float), x['gt'].to_numpy(), g_m, lv)\n"
         "        srows.append({'event': v, 'model': m, 'h': h, **FC.scores(Y, x['y'].to_numpy())})\n"
         "sc = pd.DataFrame(srows)\n"
         "MET = ['nRMSE', 'CRPS', 'PICP80', 'nMBE']\n"
         "med = sc.groupby(['model', 'h'])[MET].median().reset_index()\n"
         "for met in MET:\n"
         "    print(f'median {met}, full window:'); print(med.pivot(index='model', columns='h', values=met).round(4).to_string())\n"
         "w = sc.pivot_table(index=['event', 'h'], columns='model', values='nRMSE')\n"
         "wins = pd.DataFrame({m: pd.Series({ref: int(((w[m] < w[ref]).groupby('h').sum()).loc[C.PRIMARY_HORIZON]) for ref in ['A1', 'CLIPER', 'A5', 'LGB_level']})\n"
         "                     for m in MODELS if m.startswith('LGB')}).T\n"
         "print('units (of 10) where each LightGBM variant beats the reference at 1 h:'); print(wins.to_string())"),
    code("summary = {'notebook': 'NB5a_variants', 'environment': A.versions(), 'runtime_s': round(time.time() - t0, 1),\n"
         "           'baselines_from': {'notebook': 'NB5a_development', 'run_at': nb5['environment']['run_at'], 'models': sorted(base.model.unique())},\n"
         "           'lgb_params_pinned': LGB_PARAMS, 'variants': [f'{a}{\"_pooled\" if b else \"\"}' for a, b in VARIANTS],\n"
         "           'median_nRMSE': {m: med[med.model == m].set_index('h')['nRMSE'].round(5).to_dict() for m in MODELS},\n"
         "           'median_CRPS': {m: med[med.model == m].set_index('h')['CRPS'].round(5).to_dict() for m in MODELS},\n"
         "           'median_PICP80': {m: med[med.model == m].set_index('h')['PICP80'].round(4).to_dict() for m in MODELS},\n"
         "           'wins_at_1h_of_10': wins.to_dict('index')}\n"
         "out = A.write_outputs('nb5a_variants', {'variant_scores': sc, 'variant_medians': med, 'variant_wins_1h': wins.rename_axis('model').reset_index()},\n"
         "                      summary, parquet={'variant_forecasts': var})\n"
         "print('written to', out, '|', sorted(x.name for x in out.iterdir()))"),
]
nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3", "language": "python"}
nbf.write(nb, ROOT / "notebooks" / "NB5a_variants.ipynb")
print("wrote notebooks/NB5a_variants.ipynb")
